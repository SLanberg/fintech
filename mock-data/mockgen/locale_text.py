def text(lang: str, key: str, d=None, **kw) -> str:
    tpl = T[lang][key]
    if d is not None:
        mname = MONTHS[lang][d.month - 1]
        kw.setdefault("month", mname)
        kw.setdefault("Month", mname[:1].upper() + mname[1:])
        kw.setdefault("mm", f"{d.month:02d}")
        kw.setdefault("yyyy", str(d.year))
        kw.setdefault("q", str((d.month - 1) // 3 + 1))
    return tpl.format(**kw)


